import { z } from "zod";

import { DeviceInstanceIdSchema, EvidenceIdSchema } from "../common/identifiers.js";
import { Sha256DigestSchema } from "../common/integrity.js";
import { UtcTimestampSchema } from "../common/timestamps.js";
import { SemanticVersionSchema } from "../schema-version.js";
import { EvidenceMetadataSchema } from "./evidence.schema.js";
import { CaptureSourceSchema } from "./provenance.schema.js";

/**
 * Evidence types a client may upload through the evidence-upload operation. The original item
 * photograph arrives with the draft itself; QR-scan, recycler-receipt and reviewer-decision
 * evidence are generated by the server inside the command that needs them.
 */
export const EVIDENCE_UPLOAD_TYPES = [
  "additional_item_photo",
  "handoff_photo",
  "weight_measurement",
  "processing_completion",
] as const;

export const EvidenceUploadTypeSchema = z.enum(EVIDENCE_UPLOAD_TYPES);

/** Image media types accepted for upload. The server checks the bytes, not the declared type. */
export const UPLOAD_IMAGE_MEDIA_TYPES = ["image/jpeg", "image/png", "image/webp"] as const;

/**
 * Text fields of the multipart evidence upload. The binary travels in the `image` part. A
 * client-generated `evidence_id` makes a retried upload replay instead of duplicating.
 */
export const EvidenceUploadRequestSchema = z.strictObject({
  evidence_type: EvidenceUploadTypeSchema,
  evidence_id: EvidenceIdSchema.optional(),
  captured_at: UtcTimestampSchema,
  capture_source: CaptureSourceSchema.exclude(["system_generated"]),
  device_instance_id: DeviceInstanceIdSchema,
  connectivity: z.enum(["offline", "online"]),
  application_version: SemanticVersionSchema,
});

/** Evidence metadata for one record, in capture order. Bounded per record, so not paginated. */
export const EvidenceMetadataListSchema = z.array(EvidenceMetadataSchema).max(500);

/** Media types the protected content operation may return. */
export const PROTECTED_EVIDENCE_MEDIA_TYPES = [...UPLOAD_IMAGE_MEDIA_TYPES, "application/json"] as const;

/**
 * Delivery semantics of `GET /v1/evidence/{evidence_id}/content`, expressed over its response
 * headers. Content is served only to callers allowed to view the record, never cached, never
 * addressed by a permanent or public URL, and always accompanied by the digest of the stored
 * bytes so a client can detect a mismatch.
 */
export const ProtectedEvidenceDeliverySchema = z.strictObject({
  content_type: z.enum(PROTECTED_EVIDENCE_MEDIA_TYPES),
  cache_control: z.literal("private, no-store"),
  content_digest: Sha256DigestSchema,
});

export type EvidenceUploadRequest = z.infer<typeof EvidenceUploadRequestSchema>;
export type ProtectedEvidenceDelivery = z.infer<typeof ProtectedEvidenceDeliverySchema>;
