"""Identifier factories and formats (ADR-004).

Record, event, evidence and mutation identifiers are RFC 9562 UUIDv7 values. Human references
are display-only, and QR lookup tokens are opaque: they carry no record identifier and no
personal data.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import re
import secrets
import threading
import time
import uuid

UUID_V7_PATTERN = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"
)
HUMAN_REFERENCE_PATTERN = re.compile(r"^ST-[A-Z0-9]{8,16}$")
LOOKUP_TOKEN_PATTERN = re.compile(r"^[A-Za-z0-9_-]{24,160}$")
IDEMPOTENCY_KEY_PATTERN = re.compile(r"^[A-Za-z0-9._:-]{16,128}$")

_BASE32_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"
_LOOKUP_TOKEN_CONTEXT = b"scraptrace:qr-lookup-token:v1:"


_uuid7_lock = threading.Lock()
_uuid7_last = (0, 0)


def uuid7() -> uuid.UUID:
    """A UUIDv7: 48-bit Unix milliseconds, a 12-bit sequence and 62 random bits.

    Identifiers generated by this process are strictly increasing (RFC 9562, section 6.2,
    method 1): within one millisecond the sequence advances instead of being random, so events
    written in one transaction sort in the order they were created even when they share a
    timestamp.
    """
    global _uuid7_last
    with _uuid7_lock:
        milliseconds = time.time_ns() // 1_000_000
        last_milliseconds, last_sequence = _uuid7_last
        if milliseconds <= last_milliseconds:
            milliseconds, sequence = last_milliseconds, last_sequence + 1
            if sequence > 0xFFF:
                milliseconds, sequence = last_milliseconds + 1, 0
        else:
            sequence = secrets.randbelow(0x800)
        _uuid7_last = (milliseconds, sequence)
    raw = bytearray(milliseconds.to_bytes(6, "big") + secrets.token_bytes(10))
    raw[6] = 0x70 | (sequence >> 8)
    raw[7] = sequence & 0xFF
    raw[8] = (raw[8] & 0x3F) | 0x80
    return uuid.UUID(bytes=bytes(raw))


def is_uuid7(value: str) -> bool:
    return UUID_V7_PATTERN.fullmatch(value) is not None


def parse_uuid7(value: str) -> uuid.UUID:
    if not is_uuid7(value):
        raise ValueError("Expected a lowercase RFC 9562 UUIDv7.")
    return uuid.UUID(value)


def new_human_reference() -> str:
    """`ST-` plus ten base32 characters; unique in storage, never used for authorisation."""
    return "ST-" + "".join(secrets.choice(_BASE32_ALPHABET) for _ in range(10))


def normalize_transfer_code(value: str) -> str:
    return re.sub(r"\s+", "", value).upper()


def new_token_nonce() -> bytes:
    return secrets.token_bytes(16)


def derive_lookup_token(secret: bytes, token_id: uuid.UUID, nonce: bytes) -> str:
    """Derives the opaque QR lookup token.

    The database keeps only the token digest and this nonce. The plaintext token can be
    re-derived for the owning collector with the server-held secret, so a database copy on its
    own reveals no usable token.
    """
    mac = hmac.new(secret, _LOOKUP_TOKEN_CONTEXT + token_id.bytes + nonce, hashlib.sha256)
    return base64.urlsafe_b64encode(mac.digest()).rstrip(b"=").decode("ascii")


def lookup_token_digest(token: str) -> str:
    return hashlib.sha256(token.encode("ascii")).hexdigest()


# Manual transfer codes (ADR-009) --------------------------------------------------------------

MANUAL_TRANSFER_CODE_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
MANUAL_TRANSFER_CODE_PATTERN = re.compile(
    r"^[0-9A-HJKMNP-TV-Z]{4}-[0-9A-HJKMNP-TV-Z]{4}-[0-9A-HJKMNP-TV-Z]{4}$"
)
_MANUAL_CODE_CONTEXT = b"scraptrace:manual-transfer-code:v1:"
_MANUAL_CODE_DIGEST_CONTEXT = b"scraptrace:manual-transfer-code-digest:v1:"
_MANUAL_CODE_SYMBOLS = 12  # 12 base32 symbols = 60 bits


def derive_manual_transfer_code(secret: bytes, token_id: uuid.UUID, nonce: bytes) -> str:
    """The typed alternative to the QR, derived like the lookup token but under its own
    context label, so neither credential reveals the other. 60 bits from the MAC are written
    as three groups of four Crockford base32 symbols."""
    mac = hmac.new(secret, _MANUAL_CODE_CONTEXT + token_id.bytes + nonce, hashlib.sha256)
    value = int.from_bytes(mac.digest()[:8], "big") >> (64 - 5 * _MANUAL_CODE_SYMBOLS)
    symbols = [
        MANUAL_TRANSFER_CODE_ALPHABET[(value >> (5 * index)) & 0x1F]
        for index in reversed(range(_MANUAL_CODE_SYMBOLS))
    ]
    compact = "".join(symbols)
    return f"{compact[:4]}-{compact[4:8]}-{compact[8:]}"


def normalize_manual_transfer_code(value: str) -> str | None:
    """`normalizeManualTransferCode` from the contracts: upper case, separators removed,
    Crockford aliases applied (O->0, I/L->1), then regrouped. None if it cannot be a code."""
    compact = re.sub(r"[\s-]", "", value.upper()).replace("O", "0")
    compact = compact.replace("I", "1").replace("L", "1")
    if len(compact) != _MANUAL_CODE_SYMBOLS:
        return None
    grouped = f"{compact[:4]}-{compact[4:8]}-{compact[8:]}"
    return grouped if MANUAL_TRANSFER_CODE_PATTERN.fullmatch(grouped) else None


def manual_transfer_code_digest(secret: bytes, code: str) -> str:
    """Keyed digest stored for lookup. Keying with the server secret means a copy of the
    database alone does not allow an offline search of the 60-bit code space."""
    return hmac.new(
        secret, _MANUAL_CODE_DIGEST_CONTEXT + code.encode("ascii"), hashlib.sha256
    ).hexdigest()
