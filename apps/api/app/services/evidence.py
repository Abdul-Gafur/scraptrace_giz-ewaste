"""Evidence upload, metadata and controlled content retrieval.

Uploads are validated and re-encoded before storage, stored under a server-generated key, and
recorded with SHA-256 digest and provenance in the same transaction that re-checks the record's
state. If that transaction fails, the stored object is deleted, so no metadata points at a
missing object and no object is left without metadata. A digest detects later change to the
stored bytes; it does not prove that what the photograph shows is true.

Upload policy (who may add which evidence type, in which record state):

| Role      | Evidence types                                   | Record state                  |
|-----------|--------------------------------------------------|-------------------------------|
| collector | `additional_item_photo` (own record)             | `draft`                       |
| recycler  | `handoff_photo`, `weight_measurement`            | `awaiting_handoff`            |
| recycler  | `processing_completion`                          | `received`                    |
| recycler  | any of the three recycler types                  | `under_review` with a         |
|           |                                                  | correction request open       |

`original_item_photo` arrives with the draft itself; QR-scan, receipt and reviewer-decision
evidence are generated by the server inside the command that needs them.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass
from typing import Any

from apps.api.app.container import AppServices
from apps.api.app.contracts import mappers
from apps.api.app.core.errors import (
    ApiError,
    invalid_transition,
    not_found,
    permission_denied,
    validation_failed,
)
from apps.api.app.db.models import Evidence, RecoveryRecord
from apps.api.app.domain.identifiers import uuid7
from apps.api.app.domain.integrity import canonicalize_json, sha256_bytes
from apps.api.app.domain.time import parse_timestamp
from apps.api.app.repositories.records import RecoveryRecordRepository
from apps.api.app.services.audit import RequestContext
from apps.api.app.services.authorization import Actor, FacilityMode, RecordScope, context_for
from apps.api.app.services.evidence_storage import EvidenceStorageError, object_key_for
from apps.api.app.services.image_validation import SanitizedImage
from apps.api.app.services.records import RecordService, audience_for
from sqlalchemy.ext.asyncio import AsyncSession

# Evidence generated by the API itself carries this fixed device-instance identifier.
SERVER_DEVICE_INSTANCE_ID = uuid.UUID("0199c0de-0000-7000-8000-000000000001")
SERVER_APPLICATION_VERSION = "0.1.0"

COLLECTOR_SOURCES = frozenset({"in_app_camera", "approved_demo_fixture"})
RECYCLER_SOURCES = frozenset({"recycler_camera", "document_scanner", "approved_demo_fixture"})
RECYCLER_TYPES_BY_STATE = {
    "awaiting_handoff": frozenset({"handoff_photo", "weight_measurement"}),
    "received": frozenset({"processing_completion"}),
}
CORRECTION_TYPES = frozenset({"handoff_photo", "weight_measurement", "processing_completion"})


@dataclass(frozen=True)
class EvidenceUpload:
    evidence_type: str
    evidence_id: uuid.UUID | None
    captured_at: str
    capture_source: str
    device_instance_id: uuid.UUID
    connectivity: str
    application_version: str


@dataclass(frozen=True)
class EvidenceContent:
    content: bytes
    mime_type: str
    evidence_id: uuid.UUID


def storage_unavailable() -> ApiError:
    return ApiError(
        status_code=503,
        code="DEPENDENCY_UNAVAILABLE",
        message="Evidence storage is unavailable. The upload was not recorded; try again.",
        retryable=True,
    )


class EvidenceService:
    def __init__(self, session: AsyncSession, services: AppServices, context: RequestContext):
        self.session = session
        self.services = services
        self.context = context
        self.records = RecoveryRecordRepository(session)
        self.record_service = RecordService(session, services, context)

    def represent(self, item: Evidence, actor: Actor, record: RecoveryRecord) -> dict[str, Any]:
        data = mappers.evidence(item, personal_data=audience_for(actor, record).personal_data)
        self.services.contracts.check_response("evidence", data)
        return data

    @staticmethod
    def _visible(item: Evidence, actor: Actor) -> bool:
        # Decision evidence embeds the reviewer's note, which is Restricted to review roles.
        return item.evidence_type != "reviewer_decision" or actor.role in (
            "programme_reviewer",
            "programme_manager",
        )

    # Upload ----------------------------------------------------------------------------------

    async def _authorize_upload(
        self, actor: Actor, record: RecoveryRecord, upload: EvidenceUpload
    ) -> None:
        authorizer = self.services.authorizer
        scope = RecordScope.of(record)
        if actor.role == "collector":
            await authorizer.require(
                actor,
                "recovery_record:correct_own",
                context_for(actor, scope),
                self.context,
                target_type="recovery_record",
                target_id=record.id,
            )
            allowed_types, allowed_sources = frozenset({"additional_item_photo"}), COLLECTOR_SOURCES
            if record.business_state != "draft":
                raise invalid_transition(
                    "Photographs can be added to a record only while it is a draft.",
                    reason="NOT_A_DRAFT",
                )
        elif actor.role == "recycler":
            case = record.review_case
            correcting = (
                record.business_state == "under_review"
                and case is not None
                and case.status == "awaiting_information"
            )
            # Before handoff the QR presentation, not a destination, decides the facility.
            mode: FacilityMode = (
                "lenient" if record.business_state == "awaiting_handoff" else "strict"
            )
            permission = (
                "handoff:record"
                if record.business_state == "awaiting_handoff"
                else "processing:record"
            )
            await authorizer.require(
                actor,
                permission,
                context_for(actor, scope, facility_mode=mode),
                self.context,
                target_type="recovery_record",
                target_id=record.id,
            )
            allowed_types = (
                CORRECTION_TYPES
                if correcting
                else RECYCLER_TYPES_BY_STATE.get(record.business_state, frozenset())
            )
            allowed_sources = RECYCLER_SOURCES
            if not allowed_types:
                raise invalid_transition(
                    "Evidence cannot be added in the record's current state.",
                    reason="EVIDENCE_NOT_ACCEPTED",
                )
        else:
            # No other role holds an evidence-adding permission; this records the refusal.
            await authorizer.require_role_permission(
                actor, "handoff:record", self.context, "recovery_record", record.id
            )
            raise permission_denied()
        if upload.evidence_type not in allowed_types:
            raise validation_failed(
                "This evidence type cannot be added by this role in the record's current state.",
                "evidence_type",
                "not_permitted",
            )
        if upload.capture_source not in allowed_sources:
            raise validation_failed(
                "The capture source is not valid for this role.", "capture_source", "not_permitted"
            )

    async def upload(
        self, record_id: uuid.UUID, actor: Actor, upload: EvidenceUpload, image: SanitizedImage
    ) -> tuple[int, dict[str, Any]]:
        self.record_service.ensure_not_future(upload.captured_at, "captured_at")
        digest = sha256_bytes(image.content)
        evidence_id = upload.evidence_id or uuid7()

        async with self.session.begin():
            record = await self.records.get(record_id)
            if record is None:
                raise not_found()
            await self._authorize_upload(actor, record, upload)
            existing = await self.records.get_evidence(evidence_id)
            if existing is not None:
                return self._replay(existing, record, actor, digest)

        storage = self.services.evidence_storage
        object_key = object_key_for(record_id, evidence_id)
        try:
            stored = await storage.put(object_key, image.content, image.mime_type)
        except EvidenceStorageError as exc:
            raise storage_unavailable() from exc
        try:
            async with self.session.begin():
                record = await self.records.get(record_id, for_update=True)
                if record is None:
                    raise not_found()
                # Re-check under the row lock: the state may have moved since the first read.
                await self._authorize_upload(actor, record, upload)
                now = self.services.clock()
                item = Evidence(
                    id=evidence_id,
                    record_id=record.id,
                    evidence_type=upload.evidence_type,
                    storage_provider=stored.provider,
                    object_key=stored.object_key,
                    object_version=stored.object_version,
                    mime_type=image.mime_type,
                    file_size_bytes=len(image.content),
                    content_digest=digest,
                    image_width=image.width,
                    image_height=image.height,
                    metadata_stripped=True,
                    capture_source=upload.capture_source,
                    captured_by_id=actor.user_id,
                    captured_by_programme_id=actor.programme_id,
                    captured_by_facility_id=actor.facility_id,
                    device_instance_id=upload.device_instance_id,
                    captured_at=parse_timestamp(upload.captured_at),
                    server_received_at=now,
                    application_version=upload.application_version,
                    connectivity=upload.connectivity,
                    validation_status="accepted",
                    created_at=now,
                    updated_at=now,
                )
                self.records.add_evidence(item)
                self.services.audit.add(
                    self.session,
                    self.services.audit.event(
                        action="evidence.uploaded",
                        outcome="succeeded",
                        context=self.context,
                        actor=actor,
                        target_type="evidence",
                        target_id=evidence_id,
                        programme_id=record.programme_id,
                        facility_id=actor.facility_id,
                        details={
                            "evidence_type": upload.evidence_type,
                            "record_id": str(record.id),
                        },
                    ),
                )
                await self.session.flush()
                return 201, self.represent(item, actor, record)
        except BaseException:
            await storage.delete(object_key)
            raise

    def _replay(
        self, existing: Evidence, record: RecoveryRecord, actor: Actor, digest: str
    ) -> tuple[int, dict[str, Any]]:
        """A client-generated evidence ID makes uploads retry-safe: the same content from the
        same actor replays the stored metadata; anything else is a conflict."""
        if (
            existing.record_id != record.id
            or existing.captured_by_id != actor.user_id
            or existing.content_digest != digest
        ):
            raise ApiError(
                status_code=409,
                code="IDEMPOTENCY_CONFLICT",
                message="This evidence identifier is already used for different content.",
            )
        return 200, self.represent(existing, actor, record)

    async def store_generated(
        self,
        record: RecoveryRecord,
        actor: Actor,
        evidence_type: str,
        document: dict[str, Any],
    ) -> Evidence:
        """Stores a server-generated JSON evidence document (QR scan, recycler receipt, reviewer
        decision) inside the caller's transaction. The caller deletes the object if its
        transaction fails (see `discard_generated`)."""
        evidence_id = uuid7()
        content = canonicalize_json(document).encode("utf-8")
        try:
            stored = await self.services.evidence_storage.put(
                object_key_for(record.id, evidence_id), content, "application/json"
            )
        except EvidenceStorageError as exc:
            raise storage_unavailable() from exc
        now = self.services.clock()
        item = Evidence(
            id=evidence_id,
            record_id=record.id,
            evidence_type=evidence_type,
            storage_provider=stored.provider,
            object_key=stored.object_key,
            object_version=stored.object_version,
            mime_type="application/json",
            file_size_bytes=len(content),
            content_digest=sha256_bytes(content),
            metadata_stripped=False,
            capture_source="system_generated",
            captured_by_id=actor.user_id,
            captured_by_programme_id=actor.programme_id,
            captured_by_facility_id=actor.facility_id,
            device_instance_id=SERVER_DEVICE_INSTANCE_ID,
            captured_at=now,
            server_received_at=now,
            application_version=SERVER_APPLICATION_VERSION,
            connectivity="online",
            validation_status="accepted",
            created_at=now,
            updated_at=now,
        )
        self.records.add_evidence(item)
        return item

    async def discard_generated(self, items: list[Evidence]) -> None:
        for item in items:
            await self.services.evidence_storage.delete(item.object_key)

    # Retrieval -------------------------------------------------------------------------------

    async def list_for_record(self, record_id: uuid.UUID, actor: Actor) -> list[dict[str, Any]]:
        async with self.session.begin():
            record = await self.record_service.load_visible(record_id, actor)
            items = await self.records.list_evidence(record_id)
            return [
                self.represent(item, actor, record) for item in items if self._visible(item, actor)
            ]

    async def _load(self, evidence_id: uuid.UUID, actor: Actor) -> tuple[Evidence, RecoveryRecord]:
        item = await self.records.get_evidence(evidence_id)
        if item is None:
            raise not_found()
        record = await self.record_service.load_visible(item.record_id, actor)
        if not self._visible(item, actor):
            await self.services.authorizer.deny_scope(
                actor,
                None,
                self.context,
                target_type="evidence",
                target_id=evidence_id,
                reason="restricted_evidence",
            )
        return item, record

    async def get(self, evidence_id: uuid.UUID, actor: Actor) -> dict[str, Any]:
        async with self.session.begin():
            item, record = await self._load(evidence_id, actor)
            return self.represent(item, actor, record)

    async def content(self, evidence_id: uuid.UUID, actor: Actor) -> EvidenceContent:
        async with self.session.begin():
            item, record = await self._load(evidence_id, actor)
            self.services.audit.add(
                self.session,
                self.services.audit.event(
                    action="evidence.content-accessed",
                    outcome="succeeded",
                    context=self.context,
                    actor=actor,
                    target_type="evidence",
                    target_id=evidence_id,
                    programme_id=record.programme_id,
                    details={"evidence_type": item.evidence_type},
                ),
            )
            object_key, mime_type = item.object_key, item.mime_type
        try:
            content = await self.services.evidence_storage.read(object_key)
        except EvidenceStorageError as exc:
            raise storage_unavailable() from exc
        if sha256_bytes(content) != item.content_digest:
            raise ApiError(
                status_code=409,
                code="INTEGRITY_FAILURE",
                message="Stored evidence no longer matches its recorded digest.",
            )
        return EvidenceContent(content=content, mime_type=mime_type, evidence_id=evidence_id)
