"""Evidence object storage.

Binary evidence never lives in database rows. `EvidenceStorage` is the replaceable boundary:
the local implementation serves development and the hackathon, and an S3-compatible
implementation only needs the same four methods (object keys map directly onto S3 keys; the
provider name is recorded in `Evidence.storage_reference.storage_provider`).

Object keys are generated by the server (`evidence/<record UUID>/<evidence UUID>`), never derived
from uploaded filenames. The local store refuses any key outside that shape and any path that
resolves outside its root, so path traversal is impossible even if a key were tampered with.
"""

from __future__ import annotations

import os
import re
import tempfile
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

import anyio

OBJECT_KEY_PATTERN = re.compile(
    r"^evidence/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/"
    r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
)


class EvidenceStorageError(RuntimeError):
    """Storage is unavailable or refused an operation. Messages never include paths."""


@dataclass(frozen=True)
class StoredObject:
    provider: str
    object_key: str
    size_bytes: int
    object_version: str | None = None


class EvidenceStorage(Protocol):
    provider: str

    async def put(self, object_key: str, content: bytes, content_type: str) -> StoredObject: ...

    async def read(self, object_key: str) -> bytes: ...

    async def delete(self, object_key: str) -> None: ...

    async def exists(self, object_key: str) -> bool: ...


def object_key_for(record_id: uuid.UUID, evidence_id: uuid.UUID) -> str:
    return f"evidence/{record_id}/{evidence_id}"


class LocalEvidenceStorage:
    provider = "local-filesystem"

    def __init__(self, root: Path) -> None:
        self._root = root.resolve()

    def _path(self, object_key: str) -> Path:
        if OBJECT_KEY_PATTERN.fullmatch(object_key) is None:
            raise EvidenceStorageError("Refused an evidence object key with an unexpected shape.")
        path = (self._root / object_key).resolve()
        if not path.is_relative_to(self._root):
            raise EvidenceStorageError("Refused an evidence object key outside storage.")
        return path

    def _write(self, path: Path, content: bytes) -> None:
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        if path.exists():
            raise EvidenceStorageError("Evidence objects are immutable and cannot be replaced.")
        # Write to a temporary sibling and rename, so a reader never sees a partial object.
        descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(descriptor, "wb") as handle:
                handle.write(content)
                handle.flush()
                os.fsync(handle.fileno())
            os.chmod(temporary, 0o600)
            os.replace(temporary, path)
        except BaseException:
            Path(temporary).unlink(missing_ok=True)
            raise

    async def put(self, object_key: str, content: bytes, content_type: str) -> StoredObject:
        path = self._path(object_key)
        try:
            await anyio.to_thread.run_sync(self._write, path, content)
        except OSError as exc:
            raise EvidenceStorageError("Evidence storage is unavailable.") from exc
        return StoredObject(self.provider, object_key, len(content))

    async def read(self, object_key: str) -> bytes:
        path = self._path(object_key)
        try:
            return await anyio.to_thread.run_sync(path.read_bytes)
        except OSError as exc:
            raise EvidenceStorageError("Evidence content is unavailable.") from exc

    async def delete(self, object_key: str) -> None:
        """Used only to compensate for an upload whose metadata transaction failed."""
        path = self._path(object_key)
        await anyio.to_thread.run_sync(lambda: path.unlink(missing_ok=True))

    async def exists(self, object_key: str) -> bool:
        path = self._path(object_key)
        return await anyio.to_thread.run_sync(path.is_file)
